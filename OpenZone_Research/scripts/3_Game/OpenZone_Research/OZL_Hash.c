// Детермінований хеш рядка -- для netsync-позначки вмісту зразка.
//
// Вміст зразка прихований і на клієнт не їде; їде лише число, за яким клієнт
// відрізняє «той самий вміст» від «інший», не знаючи, який саме. Регістр
// не має значення: правило порівнює вміст без регістру, і хеш мусить так само.

class OZL_Hash
{
    static int Of(string s)
    {
        if (s == "")
            return 0;
        string k = s;
        k.ToLower();
        return k.Hash();
    }
}
